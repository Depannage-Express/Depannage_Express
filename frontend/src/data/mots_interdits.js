export const detecterMotsInterdits = (texte) => {
  if (!texte || texte.trim() === '') return [];

  const normaliser = (str) =>
    str
      .toLowerCase()
      .normalize('NFD')
      .replace(/[̀-ͯ]/g, '')
      .replace(/[0@!1]/g, (c) => ({ '0': 'o', '@': 'a', '!': 'i', '1': 'i' })[c] || c);

  const texteN = normaliser(texte);

  return MOTS_INTERDITS.filter((mot) => {
    const motN = normaliser(mot);
    return texteN.includes(motN);
  });
};

export const getNiveauGravite = (motsDetectes) => {
  const grave = [
    'tuer', 'kill', 'menacer', 'threaten',
    'frapper', 'beat', 'assassin', 'murder',
    'voleur', 'thief', 'escroc', 'scammer',
    'bâtard', 'bastard', 'enculé',
  ];
  return motsDetectes.some((m) =>
    grave.some((g) => m.toLowerCase().includes(g))
  ) ? 'high' : 'medium';
};
